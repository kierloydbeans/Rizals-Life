create table if not exists public.stop_feedback (
    id bigint generated by default as identity primary key,
    stop_id integer not null,
    rating smallint not null check (rating between 1 and 5),
    comment text not null check (char_length(comment) between 1 and 1000),
    display_name text not null default 'Anonymous' check (char_length(display_name) between 1 and 80),
    created_at timestamptz not null default now()
);

create table if not exists public.journey_feedback (
    id bigint generated by default as identity primary key,
    rating smallint check (rating between 1 and 5),
    comment text not null check (char_length(comment) between 1 and 1500),
    display_name text not null default 'Anonymous' check (char_length(display_name) between 1 and 80),
    created_at timestamptz not null default now()
);

alter table public.stop_feedback enable row level security;
alter table public.journey_feedback enable row level security;

create policy "Anyone can read stop feedback" on public.stop_feedback for select using (true);
create policy "Anyone can add stop feedback" on public.stop_feedback for insert with check (true);
create policy "Anyone can read journey feedback" on public.journey_feedback for select using (true);
create policy "Anyone can add journey feedback" on public.journey_feedback for insert with check (true);

create index if not exists stop_feedback_stop_id_created_at_idx on public.stop_feedback (stop_id, created_at desc);
create index if not exists journey_feedback_created_at_idx on public.journey_feedback (created_at desc);
